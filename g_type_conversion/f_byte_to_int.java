package g_type_conversion;

public class f_byte_to_int {
    public static void main(String[] args) {
        byte num_byte = 25; // byte upto 127 acceptable
        int num_int = num_byte;
        System.out.println("Byte value = " + num_byte);
        System.out.println("Converted integer = " + num_int);
    }
}
